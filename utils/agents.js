export const EvalAgent = {
	// 逐句分析：意图 + 倾向 + 分数 + 所属维度
	analyze(text) {
		const t = (text || '').trim()
		for (const r of INTENT_RULES) {
			if (r.re.test(t)) {
				return { intent: r.intent, tendency: r.tendency, score: clamp(r.base + hashN(t, 7) - 3, 5, 99), dim: r.dim }
			}
		}
		return { intent: 'default', tendency: '质疑', score: 70 + hashN(t, 10) - 5, dim: '质疑与追问' }
	},
	// 选项事件 → 评分（正确操作高分 / 犹豫中分 / 高危低分）
	choiceEvent(choice) {
		if (choice.correct) {
			const s = choice.label + (choice.reply || '')
			const isHelp = /报警|举报|96110|110/.test(s)
			return { tendency: '理性', score: 90 + hashN(choice.label, 9), dim: isHelp ? '应对与求助' : (/核实|点破|识破|拒绝/.test(s) ? '质疑与追问' : '高危行为规避') }
		}
		if (choice.risk === '高危') return { tendency: '上当', score: 8 + hashN(choice.label, 10), dim: '高危行为规避' }
		return { tendency: '犹豫', score: 52 + hashN(choice.label, 10), dim: '情绪稳定性' }
	},
	tendencyTip(ev) {
		switch (ev.tendency) {
			case '上当': return `评估Agent：危险！您已表现出明显的配合/上当倾向（${ev.score}分）`
			case '相信': return `评估Agent：注意，您开始相信对方了（${ev.score}分）`
			case '犹豫': return `评估Agent：您在犹豫观望，请继续核实（${ev.score}分）`
			case '质疑': return `评估Agent：不错，保持质疑与追问（${ev.score}分）`
			case '理性': return `评估Agent：非常出色，您识破了风险信号（${ev.score}分）`
			default: return ''
		}
	},
	// 训练结束：汇总六维评估报告
	buildReport(sceneName, sceneType, events) {
		const list = (events && events.length) ? events : [{ score: 70, tendency: '犹豫', dim: '情绪稳定性' }]
		const score = Math.round(list.reduce((s, e) => s + e.score, 0) / list.length)
		const grade = score >= 90 ? '优秀' : score >= 75 ? '良好' : score >= 60 ? '及格' : '不及格'
		const dims = DIMS.map(name => {
			const evs = list.filter(e => e.dim === name)
			if (!evs.length) return { name, score: clamp(score + hashN(name, 11) - 5, 40, 95) }
			return { name, score: Math.round(evs.reduce((s, e) => s + e.score, 0) / evs.length) }
		})
		const fooled = list.filter(e => e.tendency === '上当').length
		const believed = list.filter(e => e.tendency === '相信').length
		const weak = dims.slice().sort((a, b) => a.score - b.score)[0]
		let summary
		if (fooled > 0) summary = `本次训练中您有 ${fooled} 次明确表示配合（转账/透露信息），属于高危上当信号。一旦资金转出将难以追回，请务必牢记：凡是让您转账、要验证码的，先挂断核实。`
		else if (believed > 0) summary = `您整体保持了戒备，但有 ${believed} 次出现相信倾向（如询问"怎么转""会不会影响我"）。骗子最擅长利用同情与恐惧，情绪被带动时请先冷静 10 秒再回复。`
		else if (score >= 90) summary = '全程冷静理性，识破了骗子的全部引导，并能主动通过官方渠道核实或报警，是非常标准的反诈应对。'
		else summary = '您没有被骗子带走，但在质疑追问上还可以更主动——多问"为什么"、多要"凭证"、多走官方渠道。'
		const adviceMap = {
			'诈骗信号识别': '复盘本场话术中的危险信号（保证收益 / 安全账户 / 涉案保密），做到看到即警觉。',
			'质疑与追问': '养成"先问三个为什么"的习惯：为什么找我？为什么不能走官方？为什么这么急？',
			'敏感信息保护': '验证码、支付密码、身份证号、人脸与屏幕共享是资金安全的最后防线，任何场景都不提供。',
			'情绪稳定性': '骗子靠制造恐惧与贪婪让人失去判断，情绪上来时先挂断电话，冷静后再处理。',
			'高危行为规避': '不转账、不垫付、不缴解冻金——所有"先交钱再办事"的都是诈骗。',
			'应对与求助': '遇到可疑情况拨打 96110 咨询；发现被骗 30 分钟内报警止付成功率最高。'
		}
		return { scene: sceneName, sceneType, score, grade, dims, summary, advices: [adviceMap[weak.name]], time: nowStr() }
	}
}

