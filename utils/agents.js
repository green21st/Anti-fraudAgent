function clamp(n, a, b) { return Math.max(a, Math.min(b, n)) }
function hashN(text, mod) {
	let h = 0
	const t = String(text || '')
	for (let i = 0; i < t.length; i++) h = (h * 31 + t.charCodeAt(i)) >>> 0
	return h % mod
}
function nowStr() {
	const d = new Date()
	const p = n => (n < 10 ? '0' + n : '' + n)
	return `${d.getMonth() + 1}-${d.getDate()} ${p(d.getHours())}:${p(d.getMinutes())}`
}
// 防重复抽取：同一池子用尽前不重复，用尽后重置但避开上一句
function pickLine(pool, usedMap, key) {
	if (!pool || !pool.length) return ''
	let used = usedMap[key] || []
	let avail = pool.map((_, i) => i).filter(i => used.indexOf(i) === -1)
	if (!avail.length) {
		const last = used[used.length - 1]
		avail = pool.map((_, i) => i).filter(i => i !== last)
		if (!avail.length) avail = [0]
		usedMap[key] = []
	}
	const idx = avail[Math.floor(Math.random() * avail.length)]
	usedMap[key] = (usedMap[key] || []).concat(idx)
	return pool[idx]
}
// 跨阶段去重：优先取最近没说过的话，实在取不到再退回普通抽取
function pickFresh(pool, session, key) {
	for (let i = 0; i < 4; i++) {
		const line = pickLine(pool, session.used, key)
		if (!line) return ''
		if (!session.recent || session.recent.indexOf(line) === -1) return line
	}
	return pickLine(pool, session.used, key)
}
// 提取用户原话中的一小段，用来做"接话"，让每轮回应都咬住用户说的内容
function quoteOf(text) {
	let t = String(text || '').replace(/[\s，。！？、；：,.!?;:…~～"“”'‘’（）()]+/g, ' ').trim()
	t = t.replace(/^(那个|就是|其实|我觉得|我想说|嗯|额|唉|哎)[，, ]*/g, '').trim()
	const seg = t.split(' ')[0] || t
	// 纯应答词不值得引用，交给话术池正常回应
	if (/^(好的|好|嗯|行|可以|收到|ok|OK|是的|对|知道了|明白了|没问题|好嘞)$/.test(seg)) return ''
	if (!seg) return ''
	return seg.length > 14 ? seg.slice(0, 14) + '…' : seg
}

